import { readFileSync } from 'node:fs';
import openapiTS, { astToString } from 'openapi-typescript';
const actual = readFileSync('apps/web/src/lib/api/schema.d.ts','utf8');
const ast = await openapiTS(new URL('../contracts/openapi.json', import.meta.url));
const expected = '/**\n * This file was auto-generated by openapi-typescript.\n * Do not make direct changes to the file.\n */\n\n' + astToString(ast);
if (actual !== expected) throw new Error('Generated API types differ. Run npm run contract:generate.');
console.log('OpenAPI generated types match.');
